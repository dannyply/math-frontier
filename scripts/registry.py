#!/usr/bin/env python3
"""Check the result registry, bind admissions to evidence, generate RESULTS.md.

  python3 scripts/registry.py check              validate every registry/<id>.json
  python3 scripts/registry.py bind <id>          record the evidence binding of a result
  python3 scripts/registry.py generate           rewrite the RESULTS.md table
  python3 scripts/registry.py generate --check   fail if the RESULTS.md table is stale

Checks: required fields; every claimed declaration is in release/manifest.json under the
record's id, and every manifest declaration of that id is claimed; every assumed hypothesis
is defined; referenced files exist.

For status "admitted" additionally: every admission item is done; audit/axioms.json covers
the declarations; the replay receipt was produced on a clean tree at a commit in the current
history, passes standard-axiom Nanoda and Comparator for every declaration (streamed or
combined receipt format), records the manifest's current statement hash for every
declaration and the current bytes of every statement file; the negative-control receipt
records a mismatch; and the evidence binding still holds.

The evidence binding (`bind`) records sha256 hashes of everything a replay depends on: the
Lean modules in the import closure of the result's declarations, the dependency pins, the
statement files and negative control, the result's manifest entries, and the verification
tools. `bind` refuses unless each of these files is byte-identical to its version at the
commit both replay receipts were produced at, and `check` verifies the same, so a binding
can only describe sources that were actually replayed. A change to any bound file
invalidates the admission until the result is replayed and bound again. Documentation, the
paper and other results' files are not bound.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BEGIN = "<!-- registry:begin (generated by scripts/registry.py; do not edit) -->"
END = "<!-- registry:end -->"
REQUIRED = ["schema", "id", "domain", "title", "summary", "status", "grade", "paper",
            "claims", "hypotheses", "admission", "open_items"]
GRADES = {"lean": "Lean (standard axioms)",
          "conditional-lean": "Conditional Lean (named premises from the literature)"}
PINS = ["lean-toolchain", "lake-manifest.json", "lakefile.toml"]
TOOLS = ["replay/replay.py", "replay/reference_cache.py", "replay/AuditRelease.lean",
         "replay/tools.lock.json", "replay/tools-src/ComparatorWorker.lean",
         "replay/tools-src/lakefile.toml", "replay/tools-src/lake-manifest.json",
         "replay/tools-src/lean-toolchain", "scripts/build.py", "scripts/audit.py"]
MANIFEST_CORE = ["name", "module", "kind", "statement_sha256", "axioms", "native_axioms",
                 "evidence_level"]
IMPORT = re.compile(r"^(?:public |private )?import\s+([\w.]+)", re.M)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def records() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((REPO / "registry").glob("*.json"))]


def is_ancestor(commit: str) -> bool:
    return subprocess.run(["git", "merge-base", "--is-ancestor", commit, "HEAD"],
                          cwd=REPO, capture_output=True).returncode == 0


def module_closure(modules: set[str]) -> list[str]:
    seen: set[str] = set()
    stack = list(modules)
    while stack:
        m = stack.pop()
        if m in seen:
            continue
        seen.add(m)
        src = REPO / (m.replace(".", "/") + ".lean")
        stack += [i for i in IMPORT.findall(src.read_text()) if i.startswith("JocelynWorkspace")]
    return sorted(seen)


def bound_files(r: dict, manifest: dict) -> dict[str, str]:
    lean = r["lean"]
    modules = {d["module"] for d in manifest["declarations"] if d.get("result") == r["id"]}
    paths = [m.replace(".", "/") + ".lean" for m in module_closure(modules)]
    paths += PINS + TOOLS
    paths += [str(p.relative_to(REPO)) for p in sorted((REPO / lean["statement_files"]).glob("*.lean"))]
    paths.append(lean["negative_control"])
    return {p: sha256_file(REPO / p) for p in paths}


def manifest_core(r: dict, manifest: dict) -> str:
    rows = sorted(({k: d.get(k) for k in MANIFEST_CORE} for d in manifest["declarations"]
                   if d.get("result") == r["id"]), key=lambda d: d["name"])
    return hashlib.sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()


def check_record(r: dict, manifest: dict) -> list[str]:
    errs = [f"missing field {k}" for k in REQUIRED if k not in r]
    if errs:
        return errs
    if r["schema"] != "frontier.result.v1":
        errs.append("schema")
    if r["grade"] not in GRADES:
        errs.append(f"unknown grade {r['grade']}")
    hyp = {h["id"] for h in r["hypotheses"]}
    claimed = [d for c in r["claims"] for d in c["declarations"]]
    for c in r["claims"]:
        errs += [f"{c['label']}: unknown hypothesis {a}" for a in c.get("assumes", []) if a not in hyp]
    in_manifest = {d["name"] for d in manifest["declarations"] if d.get("result") == r["id"]}
    errs += [f"claimed but not in manifest: {d}" for d in claimed if d not in in_manifest]
    errs += [f"in manifest but not claimed: {d}" for d in sorted(in_manifest - set(claimed))]
    paths = list(r["paper"].values()) + [v for k, v in r.get("lean", {}).items()
                                          if k not in ("receipt", "negative_receipt", "manifest_family")]
    errs += [f"missing file {p}" for p in paths if not (REPO / p).exists()]
    if r["status"] == "admitted":
        errs += [f"admission item not done: {k}" for k, v in r["admission"].items() if v.get("status") != "done"]
        audit = REPO / "audit/axioms.json"
        audited = {d["name"]: d for d in json.loads(audit.read_text())["declarations"]} if audit.exists() else {}
        by_name = {d["name"]: d for d in manifest["declarations"]}
        for d in claimed:
            if d not in audited:
                errs.append(f"not in audit/axioms.json: {d}")
            elif audited[d]["statement_sha256"] != by_name[d]["statement_sha256"]:
                errs.append(f"audit/axioms.json statement hash differs from the manifest: {d}")
        errs += check_receipts(r, claimed, by_name)
        errs += check_binding(r, manifest)
    elif r["status"] != "candidate":
        errs.append(f"unknown status {r['status']}")
    return errs


def comparator_ok(row: dict) -> bool:
    comps = row.get("comparator_comparisons")
    if comps is not None:
        return bool(comps) and all(c.get("status") == "match" for c in comps)
    return row.get("comparator", {}).get("status") == "match"


def check_receipts(r: dict, claimed: list[str], by_name: dict) -> list[str]:
    errs = []
    lean = r.get("lean", {})
    rp, np = REPO / lean.get("receipt", ""), REPO / lean.get("negative_receipt", "")
    if not rp.is_file() or not np.is_file():
        return ["replay receipts missing"]
    for path in (rp, np):
        text = path.read_text()
        local = [m for m in ("/Users/", "/home/", "/private/", "~/") if m in text]
        if local:
            errs.append(f"{path.name} contains machine-local paths {local}")
    rec = json.loads(rp.read_text())
    repo = rec["repository"]
    if not is_ancestor(repo["git_head"]):
        errs.append("receipt commit is not in the current history")
    if repo.get("git_tracked_dirty") or repo.get("git_untracked"):
        errs.append("receipt was produced on a dirty tree")
    rows = {d["name"]: d for d in rec["declarations"]}
    for d in claimed:
        row = rows.get(d, {})
        if row.get("evidence_level") != "L1" or row.get("nanoda_standard", {}).get("status") != "pass":
            errs.append(f"receipt: no standard-axiom Nanoda pass for {d}")
        if not row.get("manifest_check", {}).get("ok"):
            errs.append(f"receipt: manifest cross-check failed for {d}")
        if row.get("statement_sha256") != by_name[d]["statement_sha256"]:
            errs.append(f"receipt statement hash differs from the current manifest: {d}")
        if not comparator_ok(row):
            errs.append(f"receipt: no Comparator match for {d}")
    for s in rec.get("statements", []):
        f = REPO / s["file"]
        if not f.is_file() or sha256_file(f) != s.get("sha256"):
            errs.append(f"statement file changed since the replay: {s['file']}")
    if rec["counts"].get("failures") or rec["counts"].get("comparator_failures"):
        errs.append("receipt records failures")
    neg = json.loads(np.read_text())
    if not is_ancestor(neg["repository"]["git_head"]):
        errs.append("negative-control receipt commit is not in the current history")
    if neg["repository"].get("git_tracked_dirty") or neg["repository"].get("git_untracked"):
        errs.append("negative-control receipt was produced on a dirty tree")
    if not neg["counts"].get("comparator", {}).get("mismatch"):
        errs.append("negative control did not record a mismatch")
    return errs


def git_blob_sha256(commit: str, path: str) -> str | None:
    p = subprocess.run(["git", "show", f"{commit}:{path}"], cwd=REPO, capture_output=True)
    return hashlib.sha256(p.stdout).hexdigest() if p.returncode == 0 else None


def replayed_commit(r: dict) -> tuple[str | None, list[str]]:
    """The commit both receipts were produced at, or None with the reasons."""
    lean = r.get("lean", {})
    heads, errs = set(), []
    for key in ("receipt", "negative_receipt"):
        path = REPO / lean.get(key, "")
        if not path.is_file():
            return None, [f"{key} missing"]
        rec = json.loads(path.read_text())["repository"]
        if rec.get("git_tracked_dirty") or rec.get("git_untracked"):
            errs.append(f"{key} was produced on a dirty tree")
        heads.add(rec["git_head"])
    if len(heads) != 1:
        errs.append("the replay receipts were produced at different commits")
    return (heads.pop() if len(heads) == 1 else None), errs


def unreplayed_files(r: dict, manifest: dict) -> list[str]:
    """Bound files whose current bytes differ from the replayed commit."""
    commit, errs = replayed_commit(r)
    if commit is None:
        return errs
    out = errs[:]
    for path, digest in bound_files(r, manifest).items():
        if git_blob_sha256(commit, path) != digest:
            out.append(f"differs from the replayed commit {commit[:7]}: {path}")
    return out


def check_binding(r: dict, manifest: dict) -> list[str]:
    b = r.get("evidence_binding")
    if not b:
        return ["no evidence binding; run scripts/registry.py bind " + r["id"]]
    errs = []
    if b.get("manifest_core_sha256") != manifest_core(r, manifest):
        errs.append("manifest entries changed since binding")
    now = bound_files(r, manifest)
    for p in sorted(set(now) | set(b["files"])):
        if now.get(p) != b["files"].get(p):
            errs.append(f"changed since binding: {p}")
    return errs + unreplayed_files(r, manifest)


def table(recs: list[dict]) -> str:
    rows = ["| Result | Status | Evidence | Headline statements | Assumes | Paper |",
            "|---|---|---|---|---|---|"]
    for r in recs:
        heads = "<br>".join(f"{c['paper_ref']}: {c['statement']}" for c in r["claims"] if c.get("headline"))
        names = {h["id"]: h["name"] for h in r["hypotheses"]}
        used = sorted({a for c in r["claims"] for a in c.get("assumes", [])}, key=list(names).index)
        assumes = "; ".join(names[a] for a in used) or "nothing"
        rows.append(f"| [{r['title']}](registry/{r['id']}.json) | {r['status']} | "
                    f"{GRADES[r['grade']]} | {heads} | {assumes} | "
                    f"[PDF]({r['paper']['pdf']}) · [TeX]({r['paper']['tex']}) |")
    return "\n".join(rows)


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    manifest = json.loads((REPO / "release/manifest.json").read_text())
    recs = records()
    if cmd == "check":
        bad = 0
        for r in recs:
            errs = check_record(r, manifest)
            for e in errs:
                print(f"{r.get('id')}: {e}", file=sys.stderr)
            bad += bool(errs)
            if not errs:
                print(f"{r['id']}: {r['status']}, record consistent")
        orphans = {d["name"] for d in manifest["declarations"]} - {
            d for r in recs for c in r["claims"] for d in c["declarations"]}
        for d in sorted(orphans):
            print(f"manifest declaration not in any record: {d}", file=sys.stderr)
        return 1 if bad or orphans else 0
    if cmd == "bind":
        rid = sys.argv[2] if len(sys.argv) > 2 else ""
        path = REPO / "registry" / f"{rid}.json"
        if not path.is_file():
            print(f"no record registry/{rid}.json", file=sys.stderr)
            return 2
        r = json.loads(path.read_text())
        stale = unreplayed_files(r, manifest)
        if stale:
            print("refusing to bind: the bound sources are not those of the replay\n  "
                  + "\n  ".join(stale), file=sys.stderr)
            return 1
        r["evidence_binding"] = {"manifest_core_sha256": manifest_core(r, manifest),
                                 "files": bound_files(r, manifest)}
        path.write_text(json.dumps(r, indent=1, ensure_ascii=False) + "\n")
        print(f"{rid}: bound {len(r['evidence_binding']['files'])} files")
        return 0
    if cmd == "generate":
        target = REPO / "RESULTS.md"
        text = target.read_text()
        i, j = text.index(BEGIN) + len(BEGIN), text.index(END)
        new = text[:i] + "\n" + table(recs) + "\n" + text[j:]
        if "--check" in sys.argv:
            if new != text:
                print("RESULTS.md table is stale; run scripts/registry.py generate", file=sys.stderr)
                return 1
            print("RESULTS.md table up to date")
            return 0
        target.write_text(new)
        print("RESULTS.md table written")
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
